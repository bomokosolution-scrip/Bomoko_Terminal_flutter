/// Les textes de l'application sont écrits en français ; [tr] les traduit selon la langue choisie.
String tr(String s) {
  if (data.lang == 'fr' || s.isEmpty) return s;
  final hit = _en[s];
  if (hit != null) return hit;
  for (final r in _rules) {
    final m = r.$1.firstMatch(s);
    if (m != null) {
      return r.$2.replaceAllMapped(RegExp(r'\$(\d)'), (x) {
        final g = m.group(int.parse(x.group(1)!));
        return g == null ? '' : tr(g);
      });
    }
  }
  if (s.contains(' · ')) return s.split(' · ').map(tr).join(' · ');
  return s;
}

